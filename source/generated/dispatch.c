int game_hook_slot(uint32_t addr)
{
    int lo = 0, hi = 57 - 1;
    while (lo <= hi) {
        int m = (lo + hi) / 2;
        if (hook_addrs[m] == addr) return hook_slots[m];
        if (hook_addrs[m] < addr) lo = m + 1; else hi = m - 1;
    }
    return -1;
}

